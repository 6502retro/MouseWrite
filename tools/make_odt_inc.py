#!/usr/bin/env python3
"""make_odt_inc.py OUT.inc - static ZIP/XML pieces for src/mwod.s, from tools/mw2odt.py.

The exporter writes:  [mimetype entry][manifest entry][content.xml local header]
then streams content.xml (PROLOGUE + body + EPILOGUE), then the central directory
and end record.  Everything except the content CRC/size and the central
directory offset is fixed, so it is generated here."""
import os, struct, sys, zlib
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from mw2odt import MIMETYPE, MANIFEST, PROLOGUE, EPILOGUE

def lh(name, data, crc=None):
    crc = zlib.crc32(data) & 0xffffffff if crc is None else crc
    n = len(data)
    return struct.pack('<IHHHHHIIIHH', 0x04034b50, 10, 0, 0, 0, 0x21, crc, n, n, len(name), 0) + name

def cdh(name, data, off, crc=None):
    crc = zlib.crc32(data) & 0xffffffff if crc is None else crc
    n = len(data)
    return struct.pack('<IHHHHHHIIIHHHHHII', 0x02014b50, 10, 10, 0, 0, 0, 0x21, crc, n, n,
                       len(name), 0, 0, 0, 0, 0, off) + name

e1 = lh(b'mimetype', MIMETYPE) + MIMETYPE
e2 = lh(b'META-INF/manifest.xml', MANIFEST) + MANIFEST
off3 = len(e1) + len(e2)
h3 = lh(b'content.xml', b'', crc=0)                     # crc/sizes patched afterwards
static1 = e1 + e2 + h3
cd = cdh(b'mimetype', MIMETYPE, 0) + cdh(b'META-INF/manifest.xml', MANIFEST, len(e1))
cd3 = len(cd)
cd += cdh(b'content.xml', b'', off3, crc=0)
eocd = struct.pack('<IHHHHIIH', 0x06054b50, 0, 0, 3, 3, len(cd), 0, 0)
tail = cd + eocd

def compress(texts, ntok=31):
    """greedy phrase dictionary: bytes $01-$1F stand for phrases (one level)."""
    phrases, cur = [], list(texts)
    for tok in range(1, ntok + 1):
        best = None
        joined = b'\x00'.join(cur)
        for L in range(4, 80):
            seen = set()
            for i in range(len(joined) - L):
                sub = joined[i:i + L]
                if sub in seen or any(c < 0x20 for c in sub):
                    continue
                seen.add(sub)
                n = joined.count(sub)
                if n >= 2:
                    sav = n * (L - 1) - (L + 1)
                    if not best or sav > best[0]:
                        best = (sav, sub)
        if not best or best[0] <= 0:
            break
        phrases.append(best[1])
        cur = [t.replace(best[1], bytes([tok])) for t in cur]
    return phrases, cur

def expand(data, phrases):
    return b''.join(phrases[c - 1] if 0 < c < 0x20 else bytes([c]) for c in data)

def bytes_lines(label, data):
    out = ['%s:' % label]
    for i in range(0, len(data), 16):
        out.append('        .byte ' + ','.join('$%02X' % b for b in data[i:i + 16]))
    return '\n'.join(out)

phrases, (cpro, cepi) = compress([PROLOGUE, EPILOGUE])
assert expand(cpro, phrases) == PROLOGUE and expand(cepi, phrases) == EPILOGUE

T = []
for i in range(16):
    c = i
    for _ in range(4):
        c = (c >> 1) ^ (0xEDB88320 if c & 1 else 0)
    T.append(c)

inc = [
    '; generated by tools/make_odt_inc.py - do not edit',
    'STATIC1_LEN = %d' % len(static1),
    'H3_FIX      = %d        ; file offset of content.xml local header CRC field' % (off3 + 14),
    'TAIL_LEN    = %d' % len(tail),
    'CD3_FIX     = %d        ; offset in TAIL of entry 3 CRC field' % (cd3 + 16),
    'EOCD_OFF    = %d        ; offset in TAIL of the central directory offset' % (len(cd) + 16),
    bytes_lines('static1', static1),
    bytes_lines('tail', tail),
    bytes_lines('prologue', cpro + b'\0'),
    bytes_lines('epilogue', cepi + b'\0'),
    'dict_lo: .byte ' + ','.join('<dict%d' % i for i in range(len(phrases))),
    'dict_hi: .byte ' + ','.join('>dict%d' % i for i in range(len(phrases))),
] + [bytes_lines('dict%d' % i, ph + b'\0') for i, ph in enumerate(phrases)] + [
    'crct0:  .byte ' + ','.join('$%02X' % (t & 255) for t in T),
    'crct1:  .byte ' + ','.join('$%02X' % (t >> 8 & 255) for t in T),
    'crct2:  .byte ' + ','.join('$%02X' % (t >> 16 & 255) for t in T),
    'crct3:  .byte ' + ','.join('$%02X' % (t >> 24) for t in T),
]
open(sys.argv[1], 'w').write('\n'.join(inc) + '\n')
print('static1 %d  tail %d  prologue %d->%d  epilogue %d->%d  dictionary %d phrases %d bytes' % (
    len(static1), len(tail), len(PROLOGUE), len(cpro), len(EPILOGUE), len(cepi), len(phrases),
    sum(len(p) + 1 for p in phrases)))
